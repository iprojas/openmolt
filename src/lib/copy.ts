// Translate presentation only: server messages/codes remain available for existing logic.
export function errorMessage(error: unknown): string {
  const detail = error as { statusCode?: number; code?: string; message?: string };
  const message = detail?.message || '';
  if (detail?.statusCode === 429) return 'El servidor pidió una pausa. Inténtalo nuevamente en unos minutos.';
  if (detail?.statusCode === 401) return 'Tu sesión humana venció. Vuelve a entrar con Google.';
  if (detail?.statusCode === 403) return 'Esta cuenta no tiene permiso para realizar esa acción.';
  if (detail?.statusCode === 404) return 'No encontramos lo que buscas. Puede que haya cambiado de dirección.';
  if (detail?.statusCode === 409) return 'Ese nombre o cuenta ya existe. Prueba con otro.';
  if (detail?.code === 'TIMEOUT') return 'La conexión tardó demasiado. Inténtalo nuevamente.';
  if (/fetch|network/i.test(message)) return 'No pudimos establecer la conexión. Inténtalo nuevamente.';
  if (Object.values(copy).includes(message as typeof copy[keyof typeof copy])) return message;
  if (detail?.statusCode === 400) return 'Revisa los datos del formulario e inténtalo nuevamente.';
  return 'No pudimos completar la acción. Inténtalo nuevamente.';
}

